/**
 * Chrono City — era storefronts and advertising for the block's ground floor.
 *
 * `StorefrontsApi` is the single entry point the app (and later the era-transition
 * integration task) talks to. It owns the `0–4 m` shopfront band of every lot and
 * morphs it through the five eras:
 *
 *   * it plans every lot per era (`planShopfront` + `planAdvertising`) up front, so
 *     per-year shop names, blurbs and media are known before any geometry exists;
 *   * it builds one *variant* per `(lot, era)` lazily — frame, glazing, door,
 *     display bay, window dressing, awning, fascia sign, blade sign, transom ad
 *     strip and (on landmark and every-third lots) freestanding kerb media —
 *     painting every face from the shared sign-texture factory;
 *   * it implements `EraBlendable`: `setEra()` starts a transition and
 *     `updateEraTransition()` is called once per frame by the `TimelineRuntime`
 *     tween, cross-fading the shopfronts and ad media of the two eras so the
 *     street is never empty and never cuts;
 *   * it registers every shop and every billboard in the `InspectionRegistry`
 *     with per-year names and blurbs, on stable lot groups so the picked object
 *     does not change under the picker while eras morph;
 *   * it registers a `SceneContext` tick system that walks the animated media
 *     (neon flicker, marquee chase, video reels, LED scroll, hologram shimmer)
 *     with pure UV/emissive updates, inside the frame budget.
 *
 * Ownership boundaries (deliberate):
 *   * **The band is ours.** Meshes tagged with the band roles in `BAND_ROLES`
 *     never leave `y ∈ [0, 4]`; the only freestanding geometry (`billboard` /
 *     `ground-fixture`) stands on the sidewalk, never on the building line.
 *   * **Buildings own everything above.** This module consumes the buildings
 *     task's mount surfaces (`mountSurfaceList()` is structurally compatible) and
 *     never touches facade or roof geometry.
 *   * **Materials and textures come from the library.** One era resolves at most
 *     `MAX_STOREFRONT_MATERIALS_PER_ERA` materials, shared across all eighteen
 *     lots, and every sign face is a canvas texture generated by the material
 *     library's surface generators — no font files, no image fetches.
 *
 * Lifecycle:
 *   create    → `createStorefrontsApi({ context, timeline, materials, registry })`.
 *   consume   → `api.snapshot()`, `api.featuresFor(era)`, `api.shopNameFor(lot, era)`,
 *               `api.lotObject(lotId)` / `api.billboardObject(lotId)`.
 *   integrate → the era-transition task wires it into `main.ts`:
 *
 *   ```ts
 *   const buildings = createBuildingsApi({ context, timeline, registry });
 *   const storefronts = createStorefrontsApi({
 *     context,
 *     timeline,
 *     registry,
 *     mountSurfaces: buildings.mountSurfaceList(),
 *     materials,
 *   });
 *   ```
 */

