/** Phrase describing the media a plan actually shows. */
export function signSentences(plan: ShopfrontPlan): string {
  const classes = new Set<MediaClass>();
  for (const media of plan.mediaProfile) classes.add(mediaClass(media));
  const phrases = [...classes].filter((entry) => entry !== 'print').map(describeMedia);
  const animated = [...classes].some(isEmissiveClass);
  const body = phrases.length > 0 ? phrases.join(', ') : 'unlit painted boards';
  return animated ? `${body}, lit and animating with the hour` : `${body}, none of it lit`;
}

/** Noun for a freestanding media structure. */
export function billboardNoun(kind: AdKind): string {
  switch (kind) {
    case 'paperHoard':
      return 'hoarding';
    case 'hologramColumn':
      return 'hologram column';
    case 'videoBillboard':
      return 'video billboard';
    case 'ledBillboard':
      return 'LED billboard';
    case 'backlitBillboard':
      return 'backlit billboard';
    case 'busShelterPoster':
      return 'bus-shelter poster';
    default:
      return 'billboard';
  }
}

/** Sentence describing how a billboard is lit, for the info card. */
export function billboardBuildSentence(plan: AdvertisementPlan): string {
  const technology = describeMedia(mediaClass(plan.media));
  const motion = plan.animated ? 'The creative walks a looping reel.' : 'The creative is a single printed sheet.';
  const place =
    plan.slot === 'kerb'
      ? 'It stands on the sidewalk clear of the shopfront band.'
      : 'It hangs within the 4 m shopfront band.';
  return `This ${billboardNoun(plan.kind)} is built from ${technology}. ${motion} ${place}`;
}

function shareOf(profile: Record<MediaClass, number>): Record<MediaClass, number> {
  let total = 0;
  for (const className of MEDIA_CLASSES) total += profile[className];
  const share = createMediaProfile();
  if (total <= 0) return share;
  for (const className of MEDIA_CLASSES) share[className] = profile[className] / total;
  return share;
}

