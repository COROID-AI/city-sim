/** One lot's shopfronts + advertising for one era. */
class StorefrontVariant implements StorefrontVariantHandle {
  readonly lotId: string;
  readonly era: EraId;
  readonly plan: ShopfrontPlan;
  readonly adPlans: readonly AdvertisementPlan[];
  readonly group: THREE.Group;
  readonly billboardGroup: THREE.Group;
  readonly shopfront: ShopfrontBuildResult;
  readonly shopfrontCounts: ShopfrontFeatureCounts;
  readonly adCounts: AdFeatureCounts;
  readonly instances: number;
  readonly meshes: readonly THREE.Mesh[];
  readonly mediaProfile: Readonly<Record<MediaClass, number>>;
  readonly animatedFaces: number;
  readonly glow: number;
  readonly signHandles: readonly SignMaterialHandle[];
  /** Instances drawn at the sidewalk kerb (billboards, columns, hoardings). */
  readonly billboardInstances: number;
  /** Instances spent on advertising, in band and at the kerb. */
  readonly advertisingInstances: number;

  weight = 1;

  private glowState = 0;
  private pulseState = 0;
  private disposed = false;

  constructor(input: VariantBuildInput) {
    this.lotId = input.lot.id;
    this.era = input.plan.era;
    this.plan = input.plan;
    this.adPlans = input.adPlans;

    this.group = new THREE.Group();
    this.group.name = `storefront-lot:${input.lot.id}@${this.era}`;
    this.group.userData.chronoStorefrontLot = input.lot.id;
    this.group.userData.chronoStorefrontEra = this.era;
    this.billboardGroup = new THREE.Group();
    this.billboardGroup.name = `storefront-billboard:${input.lot.id}@${this.era}`;
    this.billboardGroup.userData.chronoStorefrontLot = input.lot.id;
    this.billboardGroup.userData.chronoStorefrontEra = this.era;
    this.group.add(this.billboardGroup);

    this.shopfront = buildShopfront({
      plan: input.plan,
      materials: input.materials,
      geometries: input.geometries,
      parent: this.group,
      random: input.random,
      fascia: input.fascia,
      decals: input.decals,
      menu: input.menu,
      valance: input.valance,
      screen: input.screen,
    });
    this.shopfrontCounts = this.shopfront.counts;

    const adCounts = createAdFeatureCounts();
    let advertisingInstances = 0;
    let billboardInstances = 0;
    const adMedia: SignMaterialHandle[] = [];
    input.adPlans.forEach((adPlan, index) => {
      const media = input.adMedia[index] ?? null;
      const built = buildAdvertisement({
        plan: adPlan,
        materials: input.materials,
        geometries: input.geometries,
        parent: adPlan.slot === 'kerb' ? this.billboardGroup : this.group,
        random: input.random,
        media,
      });
      addAdFeatureCounts(adCounts, built.counts);
      advertisingInstances += built.instances;
      if (adPlan.slot === 'kerb') billboardInstances += built.instances;
      for (const face of built.signFaces) adMedia.push(face);
    });
    this.adCounts = Object.freeze(adCounts);

    // Unique faces this variant references: the fascia, the era decal sheet, the
    // era dressing screen and every advertisement creative.
    const unique = new Set<SignMaterialHandle>([
      input.fascia,
      input.decals,
      input.menu,
      ...(input.valance ? [input.valance] : []),
      ...(input.screen ? [input.screen] : []),
      ...adMedia,
    ]);
    this.signHandles = Object.freeze([...unique]);

    const mediaProfile = createMediaProfile();
    const addMedia = (media: SignMedia, count: number): void => {
      if (count <= 0) return;
      const bucket = mediaClass(media);
      mediaProfile[bucket] += count;
    };
    addMedia(input.plan.signMedia, 1);
    addMedia(input.plan.signMedia, this.shopfront.counts.decals);
    for (const handle of adMedia) addMedia(handle.media, 1);
    if (input.plan.kerbMedia) addMedia(input.plan.kerbMedia, 1);
    if (input.screen) {
      const screenProps = SCREEN_DRESSING_KINDS.reduce(
        (sum, kind) => sum + (this.shopfront.counts.dressingByKind[kind] ?? 0),
        0,
      );
      addMedia(input.screen.media, screenProps);
    }
    this.mediaProfile = Object.freeze(mediaProfile);

    let glow = 0;
    let animated = 0;
    for (const handle of this.signHandles) {
      glow += handle.baseEmissiveIntensity;
      if (handle.animated) animated += 1;
    }
    this.glow = glow;
    this.animatedFaces = animated;
    this.glowState = glow;

    const meshes: THREE.Mesh[] = [];
    this.group.traverse((object) => {
      if ((object as THREE.Mesh).isMesh) meshes.push(object as THREE.Mesh);
    });
    this.meshes = Object.freeze(meshes);
    this.instances = this.shopfront.instances + advertisingInstances;
    this.billboardInstances = billboardInstances;
    this.advertisingInstances = advertisingInstances;

    input.parent.add(this.group);
  }

  get shopfrontInstances(): number {
    return this.shopfront.instances;
  }

  get dressingInstances(): number {
    return this.shopfront.counts.dressingItems;
  }

  get awningInstances(): number {
    return (
      this.shopfront.counts.awnings +
      this.shopfront.counts.awningValances +
      this.shopfront.counts.awningSupports +
      this.shopfront.counts.awningScallops
    );
  }

  get signageInstances(): number {
    // Lettered and printed faces of the shopfront itself; structural
    // advertising (blades, frames, kerbs) is counted in `advertisingInstances`.
    return this.shopfront.counts.signageFaces + this.shopfront.counts.decals;
  }

  get lastGlow(): number {
    return this.glowState;
  }

  get lastPulse(): number {
    return this.pulseState;
  }

  applyWeight(weight: number): void {
    this.weight = weight;
    const visible = weight > 0.002;
    this.group.visible = visible;
    this.billboardGroup.visible = visible;
  }

  /** Walks every animated face one frame; pure in `elapsedSeconds`. */
  animate(elapsedSeconds: number): { animatedFaces: number; glow: number; pulse: number } {
    if (this.disposed || !this.group.visible) {
      return { animatedFaces: 0, glow: 0, pulse: 0 };
    }
    let glow = 0;
    let pulse = 0;
    for (const handle of this.signHandles) {
      const state = handle.advance(elapsedSeconds);
      glow += state.emissiveIntensity;
      if (state.pulse > pulse) pulse = state.pulse;
    }
    this.glowState = glow;
    this.pulseState = pulse;
    return { animatedFaces: this.animatedFaces, glow, pulse };
  }

  dispose(): void {
    if (this.disposed) return;
    this.disposed = true;
    for (const mesh of this.meshes) {
      if ((mesh as THREE.InstancedMesh).isInstancedMesh) (mesh as THREE.InstancedMesh).dispose();
    }
    this.group.removeFromParent();
    this.group.clear();
    this.billboardGroup.clear();
  }
}

