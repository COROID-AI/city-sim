/** The era's shared dressing screen (CRT wall, video loop, LED panel). */
export function eraShopScreenSpec(plan: ShopfrontPlan): SignFaceSpec | null {
  const eraMedia = screenMediaFor(plan.era);
  if (!eraMedia) return null;
  const descriptor = plan.mediaProfile;
  const blocks: SignTextBlock[] = [
    Object.freeze({ text: screenHeadline(plan), role: 'title' as const }),
    Object.freeze({ text: 'TODAY ONLY', role: 'price' as const, scale: 0.16 }),
    Object.freeze({ text: descriptor.length > 0 ? plan.accentColor.toUpperCase() : '', role: 'list' as const, scale: 0.12 }),
  ];
  return {
    era: plan.era,
    media: eraMedia,
    palette: Object.freeze({
      board: '#0b0d14',
      ink: plan.glowColor,
      glow: plan.glowColor,
      trim: '#20242e',
    }),
    blocks: Object.freeze(blocks),
    widthMeters: 1.6,
    heightMeters: 1,
    longEdge: 384,
    key: `${plan.era}:screen`,
    border: false,
    note: 'dressing-screen',
  };
}

