export const STOREFRONTS_API_VERSION = 1;

/** Tick-system id this system registers under. */
export const STOREFRONTS_SYSTEM_ID = 'city-storefronts';

/** Tick order: after the buildings (`-500`), before interaction picking (`10`). */
export const STOREFRONTS_SYSTEM_ORDER = -450;

/** Blendable id handed to the timeline. */
export const STOREFRONTS_BLENDABLE_ID = 'city-storefronts-block';

/** Root group name of the storefront set. */
export const STOREFRONTS_ROOT_NAME = 'chrono-city-storefronts';

/** Prefix of a shop's inspectable id. */
export const STOREFRONT_INSPECTABLE_PREFIX = 'storefront-';

/** Prefix of a billboard's inspectable id. */
export const BILLBOARD_INSPECTABLE_PREFIX = 'billboard-';

/** Progress at which the outgoing era has fully faded away. */
export const SOURCE_FADE_START = 0.24;
export const SOURCE_FADE_END = 0.62;
/** Progress at which the incoming era has fully arrived. */
export const TARGET_RISE_START = 0.14;
export const TARGET_RISE_END = 0.54;

/** Inspectable id of one lot's shopfront. */
export function shopfrontInspectableId(lotId: string): string {
  return `${STOREFRONT_INSPECTABLE_PREFIX}${lotId}`;
}

/** Inspectable id of one lot's billboard. */
export function billboardInspectableId(lotId: string): string {
  return `${BILLBOARD_INSPECTABLE_PREFIX}${lotId}`;
}

/** Weight of the incoming era at tween progress `p`. */
export function targetEraWeight(progress: number): number {
  const p = clamp01(progress);
  return clamp01((p - TARGET_RISE_START) / (TARGET_RISE_END - TARGET_RISE_START));
}

/** Weight of the outgoing era at tween progress `p`. */
export function sourceEraWeight(progress: number): number {
  const p = clamp01(progress);
  return 1 - clamp01((p - SOURCE_FADE_START) / (SOURCE_FADE_END - SOURCE_FADE_START));
}

